const CHECKED = "2026-08-24";

/* --------------------------------------------------------------------------
 * 掲載データから集計する。ここを手で書くと選手の増減で記事だけが古くなるため、
 * 数字は必ず players.ts から導く。
 * -------------------------------------------------------------------------- */

const byLeague = leagues
  .map((l) => ({ league: l, count: players.filter((p) => p.league === l.id).length }))
  .filter((x) => x.count > 0)
  .sort((a, b) => b.count - a.count);

const byCountry = (() => {
  const m = new Map<string, number>();
  for (const { league, count } of byLeague) {
    m.set(league.country, (m.get(league.country) ?? 0) + count);
  }
  return [...m.entries()].sort((a, b) => b[1] - a[1]);
})();

const multiPlayerClubs = (() => {
  const m = new Map<string, { league: LeagueId; count: number }>();
  for (const p of players) {
    const cur = m.get(p.club);
    m.set(p.club, { league: p.league, count: (cur?.count ?? 0) + 1 });
  }
  return [...m.entries()]
    .filter(([, v]) => v.count >= 2)
    .sort((a, b) => b[1].count - a[1].count || a[0].localeCompare(b[0], "ja"));
})();

/** 国内の定額配信で全試合の視聴手段を確認できていないリーグの選手 */
const withoutBroadcast = players.filter(
  (p) => !broadcasters.some((b) => b.leagues.includes(p.league))
);

const onLoanPlayers = players
  .map((p) => ({ player: p, status: loanStatus(p) }))
  .filter((x) => x.status.onLoan);

const withoutBroadcastLeagues = [...new Set(withoutBroadcast.map((p) => p.league))]
  .map((id) => `${leagueMap[id].name}の${withoutBroadcast.filter((p) => p.league === id).length}人`)
  .join("、");

/* --------------------------------------------------------------------------
 * ランキング記事で使う集計。/rankings/ と同じ計算を共有する。
 * -------------------------------------------------------------------------- */

const THIS_YEAR = new Date().getFullYear();

/** リーグ別の平均年齢。人数が少ないリーグは平均が振れるため3人以上に絞る */
const avgAgeByLeague = byLeague
  .filter((x) => x.count >= 3)
  .map(({ league, count }) => {
    const ages = players
      .filter((p) => p.league === league.id)
      .map((p) => THIS_YEAR - Number(p.birthDate.slice(0, 4)));
    return {
      league,
      count,
      avg: ages.reduce((a, b) => a + b, 0) / ages.length,
    };
  })
  .sort((a, b) => a.avg - b.avg);

const rankRows = (id: MetricId, take: number) =>
  rankBy(metricMap[id]).slice(0, take);

/** 海を渡った年齢の中央値 */
const medianFirstMoveAge = (() => {
  const vs = rankBy(metricMap["age-first-move"]).map((r) => r.value);
  return vs.length > 0 ? vs[Math.floor(vs.length / 2)] : null;
})();

